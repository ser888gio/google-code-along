"""Generate the frontend RS schema module from backend/field_schema.py."""

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_DIR.parent
sys.path.insert(0, str(BACKEND_DIR))

from field_schema import (  # noqa: E402
    DEFERRED_ANSWER_PATTERNS,
    DIRECT_CHAT_FIELD_KEYS,
    FIELD_SCHEMA,
    OPTIONAL_FIELDS,
    REQUIRED_FIELDS,
    STRICT_DIRECT_FIELD_KEYS,
    SUGGESTABLE_DIRECT_FIELD_KEYS,
    build_sections,
)


TARGET = REPO_ROOT / "frontend" / "app" / "generated" / "rsSchema.ts"


def _json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    direct_chat_patterns = [
        {
            "key": key,
            "patterns": FIELD_SCHEMA[key].get("direct_chat_patterns", []),
        }
        for key in DIRECT_CHAT_FIELD_KEYS
    ]
    content = f"""// Generated by backend/scripts/generate_frontend_schema.py from backend/field_schema.py.
// Do not edit by hand.

export interface FieldDef {{
  key: string;
  label: string;
  required: boolean;
  directInput?: boolean;
  multiline?: boolean;
}}

export interface Section {{
  number: number;
  title: string;
  fields: FieldDef[];
}}

export const RS_SECTIONS: Section[] = {_json(build_sections())};

export const REQUIRED_FIELD_KEYS = {_json(REQUIRED_FIELDS)} as const;
export const OPTIONAL_FIELD_KEYS = {_json(OPTIONAL_FIELDS)} as const;
export const STRICT_DIRECT_FIELD_KEYS = {_json(STRICT_DIRECT_FIELD_KEYS)} as const;
export const SUGGESTABLE_DIRECT_FIELD_KEYS = {_json(SUGGESTABLE_DIRECT_FIELD_KEYS)} as const;
export const DIRECT_CHAT_FIELD_KEYS = {_json(DIRECT_CHAT_FIELD_KEYS)} as const;
export type DirectChatFieldKey = (typeof DIRECT_CHAT_FIELD_KEYS)[number];

export const DIRECT_CHAT_FIELD_PATTERNS: Array<{{
  key: DirectChatFieldKey;
  patterns: string[];
}}> = {_json(direct_chat_patterns)};

export const DEFERRED_DIRECT_ANSWER_PATTERNS = {_json(DEFERRED_ANSWER_PATTERNS)} as const;
"""
    TARGET.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()

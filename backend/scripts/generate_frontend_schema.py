"""Generate the frontend RS schema module from backend/field_schema.py."""

# ruff: noqa: E402, E501, I001

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_DIR.parent
sys.path.insert(0, str(BACKEND_DIR))

from field_schema import (  # noqa: E402
    DEFERRED_ANSWER_PATTERNS,
    DIRECT_CHAT_FIELD_KEYS,
    FIELD_SCHEMA,
    REQUIRED_FIELDS,
    build_sections,
)


TARGET = REPO_ROOT / "frontend" / "app" / "generated" / "rsSchema.ts"


def _json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    sections_json = _json(build_sections())
    required_json = _json(REQUIRED_FIELDS)
    direct_chat_key_union = " | ".join(json.dumps(key) for key in DIRECT_CHAT_FIELD_KEYS)
    deferred_patterns_json = _json(DEFERRED_ANSWER_PATTERNS)
    direct_chat_patterns = [
        {
            "key": key,
            "patterns": FIELD_SCHEMA[key].get("direct_chat_patterns", []),
        }
        for key in DIRECT_CHAT_FIELD_KEYS
    ]
    direct_chat_patterns_json = _json(direct_chat_patterns)
    content = (
        "// Generated by backend/scripts/generate_frontend_schema.py "
        "from backend/field_schema.py.\n"
        f"""// Do not edit by hand.

interface FieldDef {{
  key: string;
  label: string;
  required: boolean;
  directInput?: boolean;
  multiline?: boolean;
  validationMode?: "strict" | "soft";
  acceptanceMode?: "manual_only" | "direct_answer" | "literal_value" | "ai_suggestion_only";
  expectedShape?: string;
  exampleGood?: string;
  rubric?: string[];
}}

export interface Section {{
  number: number;
  title: string;
  fields: FieldDef[];
}}

export const RS_SECTIONS: Section[] = {sections_json};

export const REQUIRED_FIELD_KEYS = {required_json} as const;
export type DirectChatFieldKey = {direct_chat_key_union};

export const DIRECT_CHAT_FIELD_PATTERNS: Array<{{
  key: DirectChatFieldKey;
  patterns: string[];
}}> = {direct_chat_patterns_json};

export const DEFERRED_DIRECT_ANSWER_PATTERNS = {deferred_patterns_json} as const;
"""
    )
    TARGET.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
